const Block = ({ b }) => {
  if (typeof b === 'string') return <p>{b}</p>;
  if (b.strong) return <p><strong>{b.strong}</strong></p>;
  return <ul>{b.list.map((li) => <li key={li}>{li}</li>)}</ul>;
};

const Legal = ({ doc, language, setLanguage }) => {
  const d = DOCS[doc];
  return (
    <NhLayout language={language} setLanguage={setLanguage} mobileBar={<></>}>
      <main className="nh-page nh-legal">
        <header className="nh-page-hero">
          <span className="nh-eyebrow">Shop</span>
          <h1 className="nh-h1 nh-h1-page">{d.title}</h1>
          <p className="nh-lead">Τελευταία ενημέρωση: {S.updated}{language === 'en' ? ' · The legally binding text is in Greek.' : ''}</p>
          <nav className="nh-legal-toc" aria-label="Περιεχόμενα">
            {d.sections.map(([id, h]) => <a key={id} href={`#${id}`}>{h}</a>)}
          </nav>
        </header>
        {d.sections.map(([id, h, blocks]) => (
          <section key={id} id={id} className="nh-legal-sec">
            <h2>{h}</h2>
            {blocks.map((b, i) => <Block key={i} b={b} />)}
          </section>
        ))}
        <p className="nh-legal-other"><Link to={d.other[0]}>{d.other[1]} →</Link></p>
      </main>
    </NhLayout>
  );
};

export default Legal;
